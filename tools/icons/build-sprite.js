// @ts-check
/**
 * Builds the customer icon sprite `core/ui/icons.js` from Lucide (docs/design/foundations.md §8).
 *
 * Usage (once, when the icon list or the Lucide version changes):
 *   npm pack lucide-static@1.61.0 && tar -xzf lucide-static-1.61.0.tgz
 *   node tools/icons/build-sprite.js ./package
 *
 * The drawings are used unchanged (ISC licence; icons inherited from Feather: MIT). The sprite is
 * a string inside the core script, so icons cost no request and appear with the first render.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Customer icons, foundations §8.3. Keep this list short: every icon costs bytes on every visit. */
export const CUSTOMER_ICONS = [
  'plus',
  'minus',
  'x',
  'chevron-down',
  'languages',
  'info',
  'receipt-text',
  'trash-2',
  'check',
  'triangle-alert',
  'wifi-off',
  'clock',
  'map-pin',
  'utensils',
];

/**
 * @param {string} lucideDir  extracted lucide-static package folder
 * @param {string[]} names
 */
export function buildSprite(lucideDir, names) {
  const pkg = JSON.parse(readFileSync(path.join(lucideDir, 'package.json'), 'utf8'));
  const symbols = names.map((name) => {
    const svg = readFileSync(path.join(lucideDir, 'icons', `${name}.svg`), 'utf8');
    const inner = svg
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/^[\s\S]*?<svg[^>]*>/, '')
      .replace(/<\/svg>[\s\S]*$/, '')
      .replace(/\s*\n\s*/g, '')
      .replace(/ \/>/g, '/>');
    return `<symbol id="i-${name}" viewBox="0 0 24 24">${inner}</symbol>`;
  });
  return { version: pkg.version, sprite: symbols.join('') };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('Usage: node tools/icons/build-sprite.js <extracted lucide-static folder>');
    process.exit(1);
  }
  const { version, sprite } = buildSprite(dir, CUSTOMER_ICONS);
  const out = `// @ts-check
// GENERATED by tools/icons/build-sprite.js from lucide-static ${version}. Do not edit by hand.
//
// Lucide icons: ISC License, Copyright (c) Lucide Icons and Contributors.
// Icons derived from Feather: MIT License, Copyright (c) 2013-2023 Cole Bemis.
// Full notices: https://github.com/lucide-icons/lucide/blob/main/LICENSE

/** Icons in the customer sprite. */
export const ICONS = /** @type {const} */ (${JSON.stringify(CUSTOMER_ICONS)});

/** The sprite: one <symbol id="i-<name>"> per icon, drawn with <use href="#i-<name>">. */
export const SPRITE =
  ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none">${sprite}</svg>`)};
`;
  const target = fileURLToPath(new URL('../../core/ui/icons.js', import.meta.url));
  writeFileSync(target, out);
  console.log(
    `core/ui/icons.js: ${CUSTOMER_ICONS.length} icons, ${sprite.length} bytes (lucide-static ${version})`,
  );
}
