#!/usr/bin/env node
// @ts-check
/**
 * The release window of a deployment (issue #24, docs/architecture/releases.md): up to 3
 * releases on one site, `dist/public/r/<version>/`, built by tools/release/build.js (`--keep`
 * puts earlier builds next to the new one). This tool never deploys and never changes a pin.
 *
 *   node tools/release/window.js sql    --site dist/public [--status <version>=<role> ...]
 *   node tools/release/window.js check  --site dist/public [--except <slug> ...]
 *   node tools/release/window.js digest --site dist/public --version <version>
 *
 * `sql` prints the SQL that registers every release on the site in the `releases` table (role
 * from `--status`, else the newest is "stable" and the others "previous"), with the database
 * migration and formats its manifest declares, and marks every other release "retired".
 * Registering a release changes no café.
 *
 * `check` prints the query that lists the cafés pinned to a release that is NOT on the site:
 * the deploy refuses to go on while it returns a row, since those cafés would stop loading.
 * `--except` leaves out a café the deploy re-seeds itself (the demo café).
 *
 * `digest` prints one SHA-256 for a release's files (names and contents, in order): the same
 * build gives the same digest, so the deploy can check that what it built from a tag is what
 * Ahmed approved (releases.json `artifactSha256`).
 */
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { fileURLToPath } from 'node:url';
import { compareVersions, isVersion, LEGACY } from '../../platform/shell/src/releases.js';

const HELP = `Usage:
  node tools/release/window.js sql    --site <dir> [--status <version>=<role> ...] [--now <iso>]
  node tools/release/window.js check  --site <dir> [--except <slug> ...]
  node tools/release/window.js digest --site <dir> --version <version>
`;

export const MAX_WINDOW = 3;
const ROLES = ['candidate', 'stable', 'previous'];

/** @param {unknown} v */
const sql = (v) => `'${String(v).replaceAll("'", "''")}'`;

/**
 * The releases on a site, newest first, with what their manifests say.
 * @param {string} site   the folder holding r/<version>/
 * @returns {{ version: string, platformApi: number, dataSchema: number }[]}
 */
export function siteReleases(site) {
  const r = path.join(site, 'r');
  if (!existsSync(r)) return [];
  return readdirSync(r)
    .filter((v) => isVersion(v) && existsSync(path.join(r, v, 'manifest.json')))
    .map((v) => {
      const m = JSON.parse(readFileSync(path.join(r, v, 'manifest.json'), 'utf8'));
      if (m.version !== v) throw new Error(`r/${v}/manifest.json says version ${m.version}`);
      return {
        version: v,
        platformApi: Number(m.platformApi),
        dataSchema: Number(m.dataSchema ?? LEGACY.dataSchema),
      };
    })
    .sort((a, b) => compareVersions(b.version, a.version));
}

/**
 * SQL registering the site's releases (and retiring the others).
 * @param {{ version: string, platformApi: number, dataSchema: number }[]} releases  newest first
 * @param {{ statuses?: Record<string, string>, now?: string }} [o]
 */
export function registerSql(releases, o = {}) {
  if (!releases.length) throw new Error('no release on the site');
  if (releases.length > MAX_WINDOW)
    throw new Error(
      `${releases.length} releases on the site; the window holds at most ${MAX_WINDOW}`,
    );
  const now = o.now ?? new Date().toISOString();
  const statuses = o.statuses ?? {};
  for (const [v, role] of Object.entries(statuses)) {
    if (!releases.some((r) => r.version === v)) throw new Error(`${v} is not on the site`);
    if (!ROLES.includes(role)) throw new Error(`"${role}" is not one of ${ROLES.join(', ')}`);
  }
  const lines = ['-- Release window. Generated by tools/release/window.js; changes no café.'];
  releases.forEach((r, i) => {
    const status = statuses[r.version] ?? (i === 0 ? 'stable' : 'previous');
    lines.push(
      `INSERT INTO releases (version, status, platform_api, data_schema_min, data_schema_max, added_at) VALUES (${sql(r.version)}, ${sql(status)}, ${r.platformApi}, ${r.dataSchema}, ${r.dataSchema}, ${sql(now)})` +
        ` ON CONFLICT (version) DO UPDATE SET status = excluded.status, platform_api = excluded.platform_api, data_schema_min = excluded.data_schema_min, data_schema_max = excluded.data_schema_max;`,
    );
  });
  lines.push(
    `UPDATE releases SET status = 'retired' WHERE version NOT IN (${releases.map((r) => sql(r.version)).join(', ')});`,
  );
  return lines.join('\n') + '\n';
}

/**
 * The query listing cafés pinned to a release that is not on the site.
 * @param {string[]} versions
 * @param {string[]} [except]   café slugs to leave out
 */
export function strandedQuery(versions, except = []) {
  const keep = versions.map(sql).join(', ');
  const skip = except.length ? ` AND slug NOT IN (${except.map(sql).join(', ')})` : '';
  return `SELECT slug, pinned_release FROM cafes WHERE status != 'closed' AND pinned_release NOT IN (${keep})${skip} ORDER BY slug;`;
}

/**
 * One SHA-256 over a folder's files: each relative path and the SHA-256 of its contents, sorted.
 * @param {string} dir
 */
export function treeDigest(dir) {
  /** @type {string[]} */
  const lines = [];
  /** @param {string} at */
  const walk = (at) => {
    for (const name of readdirSync(at).sort()) {
      const full = path.join(at, name);
      if (statSync(full).isDirectory()) walk(full);
      else {
        const rel = path.relative(dir, full).split(path.sep).join('/');
        lines.push(`${rel} ${createHash('sha256').update(readFileSync(full)).digest('hex')}`);
      }
    }
  };
  walk(dir);
  return createHash('sha256')
    .update(lines.sort().join('\n') + '\n')
    .digest('hex');
}

async function main() {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      site: { type: 'string' },
      status: { type: 'string', multiple: true },
      except: { type: 'string', multiple: true },
      version: { type: 'string' },
      now: { type: 'string' },
      help: { type: 'boolean', short: 'h' },
    },
  });
  const command = positionals[0];
  if (values.help || !values.site || !['sql', 'check', 'digest'].includes(command ?? '')) {
    process.stdout.write(HELP);
    process.exit(values.help ? 0 : 2);
  }
  const site = path.resolve(/** @type {string} */ (values.site));
  if (command === 'digest') {
    const v = values.version ?? '';
    const dir = path.join(site, 'r', v);
    if (!isVersion(v) || !existsSync(dir)) throw new Error(`no release ${v} on the site`);
    process.stdout.write(treeDigest(dir) + '\n');
    return;
  }
  const releases = siteReleases(site);
  if (command === 'check') {
    process.stdout.write(
      strandedQuery(
        releases.map((r) => r.version),
        values.except ?? [],
      ) + '\n',
    );
    return;
  }
  /** @type {Record<string, string>} */
  const statuses = {};
  for (const pair of values.status ?? []) {
    const [v, role] = pair.split('=');
    statuses[v] = role;
  }
  process.stdout.write(registerSql(releases, { statuses, now: values.now }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    process.stderr.write(`${err.message}\n`);
    process.exit(1);
  });
}
