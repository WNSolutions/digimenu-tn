#!/usr/bin/env node
// @ts-check
/**
 * Writes the SQL that puts one café into a D1 database: its configuration, tables, menu tree
 * and first published menu snapshot, pinned to a release. Used for the demo café on preview and
 * to onboard a real café from its private folder in the deploy repository.
 *
 *   node tools/seed/seed.js --cafe cafes/demo --release 0.1.0 [--replace] [--out seed.sql]
 *
 * `--replace` first removes the café's menu, tables and configuration (never its orders,
 * customers, counters or release history). Use it on preview, or to re-import a café that is
 * not live yet. When it moves the café to another release, the move is kept in `release_pins`
 * ("seed"), so the previous release stays one tap away for a rollback (#24).
 * The SQL holds no personal data: cafés' folders never do.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { importMenuCsv, parseCsv } from '../import/menu-csv.js';
import { buildSnapshot, SNAPSHOT_SCHEMA } from '../../core/menu/snapshot.js';
import { needsWarnings } from '../../platform/shell/src/module-needs.js';
import { moduleNeeds } from '../demo/boot.js';

const HELP = `Usage: node tools/seed/seed.js --cafe <folder> --release <x.y.z> [--replace] [--notice <file.json>] [--out file.sql]

Prints the SQL that seeds the café in <folder> (info.json, menu.csv, tables.csv).
`;

/** @param {unknown} v */
export function sql(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error('not a finite number');
    return String(v);
  }
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (typeof v === 'object') v = JSON.stringify(v);
  return `'${String(v).replaceAll("'", "''")}'`;
}

/** @param {string} table @param {Record<string, unknown>} row */
const insert = (table, row) =>
  `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(sql).join(', ')});`;

/**
 * SQL that adds a privacy notice version if it is not there yet (versions are never edited).
 * @param {string} file  JSON with version, short, full, optIn (LocalizedText each)
 * @param {string} [now]
 */
export function noticeSql(file, now = new Date().toISOString()) {
  const n = JSON.parse(readFileSync(file, 'utf8'));
  if (!Number.isInteger(n.version) || !n.short?.fr || !n.full?.fr)
    throw new Error('notice needs version, short.fr and full.fr');
  return `INSERT INTO privacy_notice_versions (version_no, short_text, full_text, opt_in_text, published_at) VALUES (${sql(n.version)}, ${sql(n.short)}, ${sql(n.full)}, ${sql(n.optIn ?? {})}, ${sql(now)}) ON CONFLICT (version_no) DO NOTHING;\n`;
}

/**
 * @param {{ dir: string, release: string, replace?: boolean, now?: string, status?: string }} o
 */
export function seedSql({ dir, release, replace = false, now = new Date().toISOString(), status }) {
  const info = JSON.parse(readFileSync(path.join(dir, 'info.json'), 'utf8'));
  const menuCsv = readFileSync(path.join(dir, 'menu.csv'), 'utf8');
  const tablesCsv = readFileSync(path.join(dir, 'tables.csv'), 'utf8');
  const imported = importMenuCsv(menuCsv, { languages: info.languages.enabled });
  if (imported.skipped.length) {
    throw new Error(
      `menu.csv has rows to fix:\n  ${imported.skipped.map((p) => `row ${p.row}: ${p.message}`).join('\n  ')}`,
    );
  }
  const { snapshot, problems } = buildSnapshot(imported.source, 1);
  if (problems.length) throw new Error(`menu problems:\n  ${problems.join('\n  ')}`);

  const cafeId = `cafe-${info.slug}`;
  const body = JSON.stringify(snapshot);
  const lines = [
    `-- Seed for café "${info.slug}" (release ${release}). Generated by tools/seed/seed.js.`,
  ];

  if (replace) {
    // Children first (foreign keys). The café row itself is kept and updated below, so its
    // orders, customers and counters stay attached.
    for (const t of [
      'variants',
      'items',
      'sub_groups',
      'categories',
      'menu_snapshots',
      'menu_changes',
      'tables',
    ]) {
      lines.push(`DELETE FROM ${t} WHERE cafe_id = ${sql(cafeId)};`);
    }
  }

  lines.push(
    `INSERT INTO releases (version, status, platform_api, data_schema_min, data_schema_max, added_at) VALUES (${sql(release)}, 'stable', 1, 1, 1, ${sql(now)}) ON CONFLICT (version) DO NOTHING;`,
    // An existing café moved to another release: the move is history (before the café row
    // changes, so the release it ran before is known).
    `INSERT OR IGNORE INTO release_pins (id, cafe_id, release, previous_release, pinned_by, reason, config_version, pinned_at) SELECT ${sql(`pin-${info.slug}-${now}`)}, id, ${sql(release)}, pinned_release, 'seed', 'seed', 1, ${sql(now)} FROM cafes WHERE id = ${sql(cafeId)} AND pinned_release != ${sql(release)};`,
    insert('cafes', {
      id: cafeId,
      slug: info.slug,
      status: status ?? (info.status === 'demo' ? 'demo' : 'onboarding'),
      pinned_release: release,
      active_config_version: 1,
      menu_rev: 1,
      created_at: now,
    }).replace(
      /;$/,
      ` ON CONFLICT (id) DO UPDATE SET pinned_release = excluded.pinned_release, active_config_version = 1, menu_rev = 1;`,
    ),
    ...(replace ? [`DELETE FROM config_versions WHERE cafe_id = ${sql(cafeId)};`] : []),
    insert('config_versions', {
      cafe_id: cafeId,
      version_no: 1,
      schema_version: info.schemaVersion ?? 1,
      body: info,
      status: 'active',
      created_by: 'seed',
      created_at: now,
    }),
    `INSERT INTO release_pins (id, cafe_id, release, previous_release, pinned_by, reason, config_version, pinned_at) SELECT ${sql(`pin-${info.slug}-1`)}, ${sql(cafeId)}, ${sql(release)}, NULL, 'seed', 'first seed', 1, ${sql(now)} WHERE NOT EXISTS (SELECT 1 FROM release_pins WHERE cafe_id = ${sql(cafeId)});`,
  );

  const rows = parseCsv(tablesCsv);
  rows.shift();
  for (const [label, code] of rows) {
    if (!label?.trim()) continue;
    lines.push(
      insert('tables', {
        cafe_id: cafeId,
        label: label.trim(),
        check_code: (code ?? '').trim().toUpperCase(),
        code_version: 1,
        active: 1,
      }),
    );
  }

  imported.source.categories.forEach((c, ci) => {
    lines.push(
      insert('categories', {
        id: c.id,
        cafe_id: cafeId,
        sort: c.sort ?? ci,
        title: c.title,
        subtitle: c.subtitle ?? null,
        visible: c.visible ?? true,
      }),
    );
    c.groups.forEach((g, gi) => {
      lines.push(
        insert('sub_groups', {
          id: g.id,
          cafe_id: cafeId,
          category_id: c.id,
          sort: g.sort ?? gi,
          title: g.title ?? null,
          description: g.description ?? null,
        }),
      );
      g.items.forEach((it, ii) => {
        lines.push(
          insert('items', {
            id: it.id,
            cafe_id: cafeId,
            category_id: c.id,
            sub_group_id: g.id,
            sort: it.sort ?? ii,
            name: it.name,
            description: it.description ?? null,
            available: it.available ?? true,
            // Modules' data for the item (#29), e.g. { "dietary_tags": { "tags": ["vegan"] } }.
            ext: it.ext ?? {},
          }),
        );
        it.variants.forEach((v, vi) => {
          lines.push(
            insert('variants', {
              id: v.id,
              cafe_id: cafeId,
              item_id: it.id,
              sort: v.sort ?? vi,
              name: v.name ?? null,
              price: v.price,
              available: v.available ?? true,
            }),
          );
        });
      });
    });
  });

  lines.push(
    insert('menu_snapshots', {
      cafe_id: cafeId,
      rev: 1,
      schema_version: SNAPSHOT_SCHEMA,
      built_by_release: release,
      sha256: createHash('sha256').update(body).digest('hex'),
      body,
      created_at: now,
    }),
    insert('menu_changes', {
      id: `chg-${info.slug}-seed`,
      cafe_id: cafeId,
      rev: 1,
      entity: 'menu',
      entity_id: cafeId,
      field: '*',
      before: null,
      after: null,
      actor_role: 'maintainer',
      source: 'seed',
      at: now,
    }),
  );
  return lines.join('\n') + '\n';
}

/**
 * What a maintainer should know before seeding, without stopping it (e.g. "google_review is
 * switched on but has no settings.reviewUrl: it stays off until it is filled in").
 * @param {string} dir
 * @returns {string[]}
 */
export function seedWarnings(dir) {
  const info = JSON.parse(readFileSync(path.join(dir, 'info.json'), 'utf8'));
  return needsWarnings(info, moduleNeeds());
}

function run() {
  const { values } = parseArgs({
    options: {
      cafe: { type: 'string' },
      release: { type: 'string' },
      replace: { type: 'boolean', default: false },
      out: { type: 'string' },
      notice: { type: 'string' },
      help: { type: 'boolean', short: 'h', default: false },
    },
  });
  if (values.help || !values.cafe || !values.release) {
    process.stdout.write(HELP);
    if (!values.help) process.exitCode = 1;
    return;
  }
  const text =
    (values.notice ? noticeSql(path.resolve(values.notice)) : '') +
    seedSql({ dir: path.resolve(values.cafe), release: values.release, replace: values.replace });
  for (const w of seedWarnings(path.resolve(values.cafe))) process.stderr.write(`warning: ${w}\n`);
  if (values.out) writeFileSync(values.out, text);
  else process.stdout.write(text);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  try {
    run();
  } catch (err) {
    process.stderr.write(`${err instanceof Error ? err.message : err}\n`);
    process.exitCode = 1;
  }
}
